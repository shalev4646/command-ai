def destination_for(question: str) -> dict | None:
    """לאן שולחים את מי ששאל שאלה שאף פקודה לא עונה עליה.

    מוחזר `None` כשאין דלת מאומתת — וזה המצב הנפוץ. הקורא אמור לקרוא לפונקציה
    **רק** אחרי שהתשובה כבר הודתה במחסור (`scope_routes.MARK_MISSING` או
    `MARK_OUT_OF_SCOPE` בגוף התשובה); המודול אינו מנחש אם הייתה תשובה.
    """
    q = question or ""
    for _, pattern, dest in _FAMILIES:
        if pattern.search(q):
            return dest
    return None


def family_of(question: str) -> str | None:
    """שם המשפחה שהתאימה — לטלמטריה ולבדיקות, לא לתצוגה."""
    q = question or ""
    for name, pattern, _ in _FAMILIES:
        if pattern.search(q):
            return name
    return None
