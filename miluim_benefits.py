def tagmul_estimate(monthly_salary: float | None) -> dict | None:
    """הערכת תגמול יומי: ברוטו 3 חודשים / 90, בטווח המינימום-מקסימום.

    הערכה בלבד — המחשבון הרשמי של ביטוח לאומי הוא הקובע. פיצוי ה-25%
    לעצמאים ותוספות מכוח הוראות שעה אינם נכללים."""
    if not monthly_salary or monthly_salary <= 0:
        return None
    daily = round(min(max(monthly_salary * 3 / 90.0, _TAGMUL_MIN_DAILY),
                      _TAGMUL_MAX_DAILY), 2)
    return {
        "daily": daily,
        "min_daily": _TAGMUL_MIN_DAILY,
        "max_daily": _TAGMUL_MAX_DAILY,
        "cite": _TAGMUL_CITE,
        "asof": _TAGMUL_ASOF,
        "link": _BTL_RATES,
    }


