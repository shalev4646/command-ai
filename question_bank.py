"""Display-layer curation of the suggested-question chips.

The chips on the greeting screen come from each order's `suggested_questions`
(LLM-written at ingestion time, pooled by `backend.get_suggested_questions`).
A 2026-08-08 sweep read all 811 of them as a soldier would — four at random on
an empty screen, no prior context — and 86 did not survive that reading. The
one the user reported is the archetype:

    "מה רמת הסיווג הביטחוני שאני צריך לשמור על תיעוד ותכתובת בנושא הזה?"

"בנושא הזה" points at a context that does not exist on an empty screen, and
the rest is order-language nobody types. Same class, 86 times.

WHY THIS IS A DISPLAY LAYER AND NOT AN EDIT TO json_store
---------------------------------------------------------
Those exact strings are also RETRIEVAL ANCHORS: `vector_store._doc_chunks`
indexes every `suggested_questions` entry as a `__sq<i>` chunk whose only job
is to give a question-to-question match that lifts the order's real chunks
(see the comment at vector_store.py, "Suggested questions are indexed as
retrieval *anchors* only"). Rewriting them in place would therefore change
retrieval — a re-embed, a moved `embedding_cache.npz`, and a re-run of both
gates — in the middle of a parallel session that owns the corpus. So the
anchors stay untouched and byte-identical, and only what the USER SEES is
curated here.

Every replacement was verified the free way (`vs.retrieve(q, n_results=8,
doc_ids=<role's docs>)`, no router, no API cost): tapping the new wording must
still put its own order's chunks into the answer context. 72 did — 58 of them
at rank 1. The 14 that did not are hidden with no replacement: the pool holds
811 questions and shows four, so removing a chip costs nothing, while showing
one that leads nowhere costs the user's trust.

PROMOTION PATH: once the corpus session is done, each replacement below can
move into its order's `suggested_questions` with the original moved to
`anchor_questions` — the pattern already used when the display questions were
rewritten per role. Until then this table is the single place they live.
"""

