def curate(questions: list[str]) -> list[str]:
    """Filter and rewrite a raw chip pool for display.

    Order is preserved (the caller samples from it) and duplicates are dropped —
    two orders occasionally ship the same phrasing, and the same question twice
    on one screen reads as a bug.
    """
    out: list[str] = []
    seen: set[str] = set()
    for q in questions:
        if not isinstance(q, str):
            continue
        q = q.strip()
        if q in _CURATED:
            q = _CURATED[q]
            if not q:
                continue
        elif _DEIXIS.search(q) or len(q) > _MAX_CHARS:
            # unseen question with a known defect: hide rather than guess
            continue
        if len(q) < 12 or q in seen:
            continue
        seen.add(q)
        out.append(q)
    return out
