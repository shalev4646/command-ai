def prompt_block() -> str:
    """The allowed-frameworks list as the model sees it.

    Deliberately keyless. The first live run (10.08.2026) emitted
    `**לא נקבע בפקודות מטכ"ל:** civil_law — …` — the model copied the dict KEY,
    so an English internal identifier landed in a Hebrew answer to a soldier.
    Nothing the model is shown should be a name it must not repeat, so the keys
    stay out and `where` goes in: with the destination in front of it the model
    routes from the table instead of composing a plausible-sounding referral.
    """
    lines = []
    for v in ROUTES.values():
        where = f" · לאן פונים: {v['where']}" if v["where"] else ""
        lines.append(f"- {v['label']} — {v['covers']}{where}")
    return "\n".join(lines)


